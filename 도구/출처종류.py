"""기사 문장이 인용한 출처의 종류를 규칙으로 가린다(LLM 호출 없음).

종류마다 결론 문구가 달라야 '못 찾음'이 '기사가 틀림'으로 읽히지 않는다.
근거: reports/원래 어디서 약점 연구 사례.md (Spangher 외 출처 귀속, AAP '확인 불가' 정의)

- 의원실 자료: 국회의원이 기관에서 제출받은 자료 → 공개 원문이 없을 수 있음(원 보고서 검색 안 함)
- 원자료 분석: KOSIS 통계표·마이크로데이터·기사가 기관 자료를 직접 분석 → 보도자료에 없으면 '통계표·원자료 인용'
- 보고서·보도자료: 기본(원문 대조)
학술지는 입구.py 에서 먼저 거른다.
"""
import re

LAWMAKER = re.compile(r"의원(?:실)?\s*(?:은|이|측|에\s*따르면|이\s*공개한|이\s*밝힌)|의원실|국정감사|국감\s*자료|"
                      r"제출받은\s*자료|에게\s*제출한\s*자료")
RAW_DATA = re.compile(r"KOSIS|국가통계포털|마이크로데이터|원자료|통계표|MDIS")
# 언론사가 통계를 직접 분석·교차 분석: '여성경제신문이 국가데이터처의 … 교차 분석한 결과'(중간 점검 #7, 새 기사 #9와 같은 유형)
PRESS_ANALYSIS = re.compile(r"(?:신문|일보|뉴스|방송|경제|타임스|기자|본지|취재팀)\S{0,2}\s*(?:이|가|은|는)?\s*.{0,60}?(?:교차\s*)?분석한\s*결과")
# 기사(또는 다른 기관)가 통계 기관의 자료를 직접 분석: '국가데이터처 자료를 분석한 결과'
# (11/13 새 기사 #9: 경기도 국제결혼 건수를 '원문에 없음'으로 답함)
OWN_ANALYSIS = re.compile(r"(?:국가데이터처|통계청|데이터처)\S{0,6}\s*(?:\S+\s*){0,3}?(?:자료|데이터|통계)를\s*(?:재?분석|분석해|집계)")

MESSAGES = {
    "의원실 자료": "국회의원실이 기관에서 제출받은 자료를 인용한 문장으로 보입니다. 이런 자료는 공개 원문이 없을 수 있어 "
                "원 보고서를 찾지 않았습니다. 기사 숫자가 틀렸다는 뜻이 아닙니다.",
    "원자료 분석": "기사가 보고서가 아니라 통계표(KOSIS)·마이크로데이터를 인용하거나 직접 분석한 숫자입니다. "
                "보도자료 PDF에 같은 숫자가 없을 수 있습니다.",
}


def classify(sentence: str) -> str:
    """'의원실 자료' / '원자료 분석' / '보고서·보도자료'."""
    if LAWMAKER.search(sentence):
        return "의원실 자료"
    if RAW_DATA.search(sentence) or OWN_ANALYSIS.search(sentence) or PRESS_ANALYSIS.search(sentence):
        return "원자료 분석"
    return "보고서·보도자료"


if __name__ == "__main__":
    for s in ['무소속 이춘석 의원은 "지자체가 요청한 174건 중 98건이 채택되지 않았다"고 설명했다.',
              "국가데이터처 자료를 분석한 결과 경기도내 국제결혼 건수는 2025년 6천77건이다.",
              "18일 국가데이터처 국가통계포털(KOSIS) 가계동향조사에 따르면 이자 비용은 21만1965원이다.",
              "한국보건사회연구원이 2024년 조사 자료를 분석한 결과 5.5%였다.",
              "국가데이터처에 따르면 지난 10월 소비자물가지수는 2.8% 상승했다."]:
        print(f"{classify(s):10} ← {s[:55]}")
